// Generates migrations/0007_learning_universe.sql: schema for the learning universe plus the verified Class 7 seed.
// Run: bun tests/gen-universe-migration.ts   (reads data/class7-question-seed.json)
// Additive only: new tables, new nullable/defaulted columns, INSERT OR IGNORE seeds. No row is deleted.
import { readFileSync, writeFileSync } from "node:fs";

type Seed = {
  questions: {
    id: string;
    key: string;
    chapterId: string;
    type: "mcq" | "numeric" | "short";
    answerKind: string;
    prompt: string;
    options: { id: string; text: string }[] | null;
    answer: string;
    explanation: string | null;
    hint: string | null;
    unit: string | null;
    skill: string | null;
    difficulty: number;
    language: "bn" | "en";
    source: "textbook_exercise" | "educerro_authored";
    status: "published" | "draft";
    printedPage: number;
    pdfPage: number;
    misconceptions?: Record<string, string> | null;
    provenance: Record<string, unknown>;
  }[];
  objectives: {
    id: string;
    chapterId: string;
    position: number;
    text: string;
    printedPage: number;
    pdfPage: number;
  }[];
};

// SHA-256 of the one-time owner bootstrap code. The code itself was given privately to the owner and is never stored.
const BOOTSTRAP_HASH = "919536ad4158793900e08e65d55d0bb81ebb984d06418d4d42c9588322eecabe";
const STAMP = "2026-10-26T00:00:00Z";

const seed = JSON.parse(
  readFileSync(new URL("../data/class7-question-seed.json", import.meta.url), "utf8"),
) as Seed;
const q = (v: unknown) =>
  v === null || v === undefined
    ? "NULL"
    : typeof v === "number"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;

const out: string[] = [];
out.push(`-- IntelliHorizon learning universe. GENERATED by tests/gen-universe-migration.ts from data/class7-question-seed.json. Do not edit by hand.
-- Additive only: new tables, new columns with defaults, INSERT OR IGNORE seeds. No row is deleted.

-- 1. Administrator access. The first-signup slot is closed for good; admin now needs the one-time owner code
--    (hash below) or the EDU_ADMIN_TOKEN secret. Each code can be claimed once.
UPDATE app_settings SET value = '0' WHERE key = 'admin_bootstrap_open';
CREATE TABLE IF NOT EXISTS admin_bootstrap (
  code_hash TEXT PRIMARY KEY,
  created_at TEXT NOT NULL,
  used_by TEXT,
  used_at TEXT
);
INSERT OR IGNORE INTO admin_bootstrap (code_hash, created_at) VALUES ('${BOOTSTRAP_HASH}', '${STAMP}');

CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  actor_id TEXT,
  action TEXT NOT NULL,
  target TEXT,
  detail TEXT,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS audit_log_at ON audit_log (created_at);

-- 2. XP ledger. One row per rewarded learning event; UNIQUE(user, kind, ref) makes every reward idempotent.
CREATE TABLE IF NOT EXISTS xp_events (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('first_correct', 'improved', 'revision', 'session_complete', 'explain', 'chapter_opened')),
  ref TEXT NOT NULL,
  xp INTEGER NOT NULL CHECK (xp BETWEEN 0 AND 50),
  session_id TEXT,
  created_at TEXT NOT NULL,
  UNIQUE (user_id, kind, ref)
);
CREATE INDEX IF NOT EXISTS xp_events_user ON xp_events (user_id, created_at);

CREATE TABLE IF NOT EXISTS user_achievements (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  achievement_id TEXT NOT NULL,
  earned_at TEXT NOT NULL,
  PRIMARY KEY (user_id, achievement_id)
);

-- 3. Learning Sessions: discover, understand, try, improve, remember, celebrate, continue.
CREATE TABLE IF NOT EXISTS learning_sessions (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  chapter_id TEXT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
  question_ids TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed')),
  started_at TEXT NOT NULL,
  completed_at TEXT
);
CREATE INDEX IF NOT EXISTS learning_sessions_user ON learning_sessions (user_id, started_at);

-- Offline answers carry a client event id; the unique index makes a re-sent answer a no-op.
ALTER TABLE attempts ADD COLUMN client_event_id TEXT;
ALTER TABLE attempts ADD COLUMN session_id TEXT;
ALTER TABLE attempts ADD COLUMN misconception TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS attempts_client_event ON attempts (user_id, client_event_id);
CREATE INDEX IF NOT EXISTS attempts_session ON attempts (session_id);

-- Explain It Back: what the student wrote and which key ideas it covered.
CREATE TABLE IF NOT EXISTS explanations (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  chapter_id TEXT NOT NULL REFERENCES chapters(id) ON DELETE CASCADE,
  session_id TEXT,
  text TEXT NOT NULL,
  covered TEXT NOT NULL,
  created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS explanations_user ON explanations (user_id, created_at);

-- Student goals and preferences.
ALTER TABLE profiles ADD COLUMN daily_goal INTEGER NOT NULL DEFAULT 5;

-- 4. Question authoring pipeline: draft -> reviewed -> published, with provenance.
ALTER TABLE questions ADD COLUMN review_status TEXT NOT NULL DEFAULT 'published';
ALTER TABLE questions ADD COLUMN answer_kind TEXT;
ALTER TABLE questions ADD COLUMN hint TEXT;
ALTER TABLE questions ADD COLUMN unit TEXT;
ALTER TABLE questions ADD COLUMN skill TEXT;
ALTER TABLE questions ADD COLUMN misconceptions TEXT;
ALTER TABLE questions ADD COLUMN provenance TEXT;
ALTER TABLE questions ADD COLUMN reviewed_by TEXT;
ALTER TABLE questions ADD COLUMN reviewed_at TEXT;
ALTER TABLE questions ADD COLUMN published_by TEXT;
ALTER TABLE questions ADD COLUMN published_at TEXT;
ALTER TABLE questions ADD COLUMN updated_at TEXT;
CREATE TRIGGER IF NOT EXISTS questions_publish_guard BEFORE UPDATE OF status ON questions
WHEN NEW.status = 'published' AND NEW.review_status != 'published'
BEGIN SELECT RAISE(ABORT, 'question_not_reviewed'); END;

-- Learning outcomes keep where they came from.
ALTER TABLE objectives ADD COLUMN review_status TEXT NOT NULL DEFAULT 'checked';
ALTER TABLE objectives ADD COLUMN source_note TEXT;

-- OCR correction: an admin's corrected text for a page is kept beside the original, never over it.
ALTER TABLE source_pages ADD COLUMN corrected_text TEXT;
ALTER TABLE source_pages ADD COLUMN corrected_by TEXT;
ALTER TABLE source_pages ADD COLUMN corrected_at TEXT;
ALTER TABLE source_pages ADD COLUMN review_state TEXT;
`);

out.push(
  `-- 5. Verified Class 7 learning outcomes (printed in the book; transcribed and checked against the page image by Claude).`,
);
for (const o of seed.objectives) {
  out.push(
    `INSERT OR IGNORE INTO objectives (id, chapter_id, position, text, source_page, bloom, created_at, review_status, source_note) VALUES (${q(o.id)}, ${q(o.chapterId)}, ${o.position}, ${q(o.text)}, ${o.pdfPage}, NULL, '${STAMP}', 'checked', ${q(`Printed page ${o.printedPage}; transcribed from the page image and checked by Claude; not yet reviewed by a teacher`)});`,
  );
}
out.push(`\n-- 6. Practice questions. Published: printed in the book, with answers from the book's own key (or computed exactly where the book prints none).
--    Draft: written by Claude from a quoted passage; hidden from students until an editor reviews and publishes them.`);
for (const x of seed.questions) {
  const pub = x.status === "published";
  out.push(
    `INSERT OR IGNORE INTO questions (id, chapter_id, type, prompt, options, answer, tolerance, explanation, source, source_page, objective_id, bloom, difficulty, language, status, created_by, created_at, review_status, answer_kind, hint, unit, skill, misconceptions, provenance, reviewed_by, reviewed_at, published_by, published_at, updated_at) VALUES (` +
      [
        q(x.id),
        q(x.chapterId),
        q(x.type),
        q(x.prompt),
        q(x.options ? JSON.stringify(x.options) : null),
        q(x.answer),
        "NULL",
        q(x.explanation),
        q(x.source),
        x.pdfPage,
        "NULL",
        "NULL",
        x.difficulty,
        q(x.language),
        q(x.status),
        q("educerro-seed"),
        q(STAMP),
        q(pub ? "published" : "draft"),
        q(x.answerKind),
        q(x.hint),
        q(x.unit),
        q(x.skill),
        q(x.misconceptions ? JSON.stringify(x.misconceptions) : null),
        q(JSON.stringify({ ...x.provenance, key: x.key, printedPage: x.printedPage })),
        pub ? q("educerro-seed") : "NULL",
        pub ? q(STAMP) : "NULL",
        pub ? q("educerro-seed") : "NULL",
        pub ? q(STAMP) : "NULL",
        q(STAMP),
      ].join(", ") +
      `);`,
  );
}
writeFileSync(
  new URL("../migrations/0007_learning_universe.sql", import.meta.url),
  out.join("\n") + "\n",
);
console.log(`wrote ${seed.questions.length} questions, ${seed.objectives.length} objectives`);
