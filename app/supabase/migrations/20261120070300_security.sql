-- Access model. The browser never talks to Supabase: every query runs on the server (Vercel) as the role ih_app.
-- Row Level Security is ON for every table. The public API roles (anon, authenticated) get no policies and no
-- table privileges, so the publishable key exposes nothing. ih_app gets explicit policies; per-student isolation
-- (a student sees only their own rows, judges are students, admin is a role) is enforced in the server code that
-- every request goes through, and is covered by the e2e tests. The role's password is set outside Git.
DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ih_app') THEN CREATE ROLE ih_app NOLOGIN; END IF; END $$;
GRANT USAGE ON SCHEMA public TO ih_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO ih_app;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO ih_app;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO ih_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ih_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO ih_app;

