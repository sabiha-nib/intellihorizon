-- Integrity guards (were SQLite triggers).
CREATE OR REPLACE FUNCTION textbooks_subject_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM subject_offerings o WHERE o.grade = NEW.grade AND o.medium = NEW.medium AND o.subject_id = NEW.subject_key) THEN
    RAISE EXCEPTION 'subject_not_in_registry';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS textbooks_subject_guard_ins ON textbooks;
CREATE TRIGGER textbooks_subject_guard_ins BEFORE INSERT ON textbooks FOR EACH ROW EXECUTE FUNCTION textbooks_subject_guard();
DROP TRIGGER IF EXISTS textbooks_subject_guard_upd ON textbooks;
CREATE TRIGGER textbooks_subject_guard_upd BEFORE UPDATE OF grade, medium, subject_key ON textbooks FOR EACH ROW EXECUTE FUNCTION textbooks_subject_guard();
CREATE OR REPLACE FUNCTION questions_publish_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'published' AND NEW.review_status <> 'published' THEN
    RAISE EXCEPTION 'question_not_reviewed';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS questions_publish_guard ON questions;
CREATE TRIGGER questions_publish_guard BEFORE UPDATE OF status ON questions FOR EACH ROW EXECUTE FUNCTION questions_publish_guard();

